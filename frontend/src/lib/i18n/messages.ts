export const messages: Record<Language, Messages> = { es, en };

export function translate(language: Language, key: string, vars?: Record<string, string | number>): string {
  const table = messages[language] ?? messages.es;
  let value = table[key] ?? messages.es[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replace(new RegExp(`\\{${name}\\}`, 'g'), String(replacement));
    }
  }
  return value;
}
